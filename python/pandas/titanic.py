print(df_sex_class.describe())

bins = [0, 13, 20, 35, 60, 100]
labels = ['child', 'teenager', 'young', 'adult', 'senior']
df['age_group'] = pd.cut(df['Age'], bins=bins, labels=labels)
survival_age = df.groupby('age_group', observed=False)
print(survival_age.describe())

