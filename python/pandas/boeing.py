import kagglehub
import pandas as pd
import matplotlib.pyplot as plt

path = kagglehub.dataset_download("nurielreuven/boeing-historical-airplane-orders-deliveries")

print("Path to dataset files:", path)

df = pd.read_csv(path+"/OrdersandDeliveries.csv")

print(df.count())
new_names = {'Delivery Year ': 'Delivery Year'}
df = df.rename(columns=new_names)
print(df)

df = df[df['Order Year'] != 'All']
df = df[df['Delivery Year'] != 'All']
df = df.dropna(subset=['Delivery Year']).copy()
print(df)

df['Order Year'] = pd.to_numeric(df['Order Year'])
df['Delivery Year'] = pd.to_numeric(df['Delivery Year'])
df['Order Total'] = pd.to_numeric(df['Order Total'].astype(str).str.replace(',',''))

month_map = {'Jan': 1, 'Feb': 2, 'Mar': 3, 'Apr': 4,
             'May': 5, 'Jun': 6, 'Jul': 7, 'Aug': 8,
             'Sep': 9, 'Oct': 10, 'Nov': 11, 'Dec': 12}
df['Order Month'] = df['Order Month'].map(month_map)
df['Order Month'].unique()

order_year_str_clean = df['Order Year'].astype(str).str.replace(r'\.0$', '', regex=True)
order_month_str_clean = df['Order Month'].astype(str).str.replace(r'\.0$', '', regex=True)
df['Order Date'] = pd.to_datetime(order_year_str_clean + '-' + order_month_str_clean + '-01')

delivery_year_str_clean = df['Delivery Year'].astype(str).str.replace(r'\.0$', '', regex=True)
df['Delivery Date'] = pd.to_datetime(delivery_year_str_clean + '-12-31')

df.head(10)

months_range = pd.date_range(start=df['Order Date'].min(),
                           end=df['Delivery Date'].max(),
                           freq='MS')
print(months_range)
results = []
for current_month in months_range:
    mask = (df['Order Date'] <= current_month) & (df['Delivery Date'] > current_month)
    total_in_progress = df.loc[mask, 'Order Total'].sum()
    results.append({'Month': current_month, 'Planes_In_Progress': total_in_progress})

prog_df = pd.DataFrame(results)
print(prog_df.tail())
print(prog_df.head())

plt.plot(prog_df['Month'], prog_df['Planes_In_Progress'],
         color='blue', linewidth=2)

plt.title('Boeing Aircraft Manufacturing Volume', fontsize=15)
plt.xlabel('Year', fontsize=12)
plt.ylabel('Number of Planes in Progress', fontsize=12)
plt.grid(True, linestyle='--')
plt.show()